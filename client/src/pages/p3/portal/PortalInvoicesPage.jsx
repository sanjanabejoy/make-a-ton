import React from 'react';
import { useNavigate } from 'react-router-dom';
import { useQuery } from '@tanstack/react-query';
import http from '../../../api/http';
import Card from '../../../components/ui/Card';
import StatusBadge from '../../../components/ui/StatusBadge';
import Money from '../../../components/ui/Money';
import DateText from '../../../components/ui/DateText';
import { Skeleton } from '../../../components/ui/Skeleton';
import EmptyState from '../../../components/ui/EmptyState';

export function PortalInvoicesPage() {
  const navigate = useNavigate();

  const { data: invoicesData, isLoading } = useQuery({
    queryKey: ['portalInvoices'],
    queryFn: async () => {
      const res = await http.get('/portal/invoices');
      return res.data || res;
    },
  });

  const invoicesList = Array.isArray(invoicesData) ? invoicesData : invoicesData?.data || [];

  if (isLoading) {
    return <Skeleton className="h-64 w-full" />;
  }

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-bold tracking-tight text-slate-900">My Invoices</h1>
        <p className="text-sm text-slate-500 mt-1">
          Access tax invoices, line-item breakdowns, and settled payments.
        </p>
      </div>

      <Card className="p-0 overflow-hidden">
        {invoicesList.length === 0 ? (
          <EmptyState
            title="No invoices found"
            description="Invoices will appear here once generated by recurring cycles."
          />
        ) : (
          <div className="divide-y divide-slate-100">
            {invoicesList.map((inv) => (
              <div
                key={inv.id}
                onClick={() => navigate(`/portal/invoices/${inv.id}`)}
                className="p-5 flex flex-col sm:flex-row sm:items-center justify-between gap-4 hover:bg-slate-50 cursor-pointer transition"
              >
                <div>
                  <div className="flex items-center gap-3">
                    <span className="font-bold text-base text-slate-900">{inv.number}</span>
                    <StatusBadge
                      status={inv.status}
                      isOverdue={inv.isOverdue}
                      daysOverdue={inv.daysOverdue}
                    />
                  </div>
                  <p className="text-xs text-slate-500 mt-1">
                    Invoice Date: <DateText date={inv.invoiceDate} /> · Due Date:{' '}
                    <DateText date={inv.dueDate} />
                  </p>
                </div>

                <div className="flex items-center gap-6">
                  <div className="text-left sm:text-right">
                    <span className="text-xs text-slate-400 uppercase tracking-wider block">
                      Total Due
                    </span>
                    <span className="text-lg font-bold font-mono text-slate-900">
                      <Money amount={inv.total} />
                    </span>
                    <span className="block text-xs text-slate-500">
                      Paid: <Money amount={inv.amountPaid || 0} />
                    </span>
                  </div>
                </div>
              </div>
            ))}
          </div>
        )}
      </Card>
    </div>
  );
}

export default PortalInvoicesPage;
